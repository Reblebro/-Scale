#include "../src/edited-mesh.hpp"
#include <cassert>
#include <cmath>
#include <iostream>

// Headless geometry test: no GL context or game assets needed.
void Geometry::triangle(Vec a,Vec b,Vec c,int id,Color color,float){
    auto normal=unit(cross(b-a,c-a));
    for(Vec p:{a,b,c}) points.push_back({float(p.x),float(p.y),float(p.z),
        float(normal.x),float(normal.y),float(normal.z),0,0,float(id),color.r,color.g,color.b});
}
void Geometry::quad(Vec a,Vec b,Vec c,Vec d,int id,Color color,float repeat){
    triangle(a,b,c,id,color,repeat);triangle(a,c,d,id,color,repeat);
}
int main(){
    terrain::LeafFaces one;
    one.add({{3,6,5},0,Stone},1,true);
    Geometry broken;
    one.draw(broken,{},Color{1,1,1});
    assert(broken.points.size()>12); // Surface is actually subdivided.
    bool displaced=false;
    for(const auto& p:broken.points){
        assert(p.x>=2.75f && p.x<=4.25f);
        assert(p.y>=5.75f && p.y<=7.25f);
        assert(p.z>=4.75f && p.z<=6.25f);
        assert(p.nx>0.0f);
        if(std::abs(p.x-4.0f)>0.0001f)displaced=true;
    }
    assert(displaced); // The perimeter is no longer fixed to the cube plane.
    // All 6 orientations retain consistently outward-pointing triangles.
    for(int side=0;side<6;++side){
        Geometry g;
        terrain::chippedSquare(g,{},1.0,side,Stone,{1,1,1});
        assert(g.points.size()>12);
        const Vec outward=Sides[side].v();
        for(const auto& v:g.points){
            assert(v.x>=-0.25f && v.x<=1.25f);
            assert(v.y>=-0.25f && v.y<=1.25f);
            assert(v.z>=-0.25f && v.z<=1.25f);
            assert(dot(Vec{v.nx,v.ny,v.nz},outward)>0.1);
        }
    }
    // Identical world-space corners warp identically when generated by two
    // separate quads, rather than opening cracks at equal-LOD shared edges.
    const Vec at{1,2,3};
    const Vec p=terrain::warpedSurfacePoint(at,{});
    const Vec q=terrain::warpedSurfacePoint(at-Vec{4,0,0},Vec{4,0,0});
    assert(length(p-(q+Vec{4,0,0}))<1e-8);
    terrain::LeafFaces untouched;
    untouched.add({{3,6,5},0,Stone},1,false);
    Geometry naturallyExposed;
    untouched.draw(naturallyExposed,{},Color{1,1,1});
    assert(naturallyExposed.points.size()>12);
    terrain::LeafFaces construction;
    construction.add({{3,6,5},0,CampTile},1,true);
    Geometry flat;
    construction.draw(flat,{},Color{1,1,1});
    assert(flat.points.size()==6);
    std::cout << "PASS: displaced world-space terrain silhouette, extra relief, winding, construction unchanged\n";
}
